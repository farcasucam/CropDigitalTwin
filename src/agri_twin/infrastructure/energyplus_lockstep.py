"""EnergyPlus driven in lock-step by an external controller, one hour per call.

EnergyPlus runs as a child process with a Python Plugin (EnergyPlus' own bundled Python) that talks to this process over a loopback TCP socket in JSON lines, as verified in
``docs/phase5_41``. At the start of every zone timestep the plugin sends the time and waits for the commands of the hour; at the end of the timestep it sends the zone values. One
call to ``LockstepSession.advance`` is one simulated hour (four timesteps) with the commands held for the whole hour, which is what lets a controller decide from the state at the
end of the previous hour, like the simplified model, instead of from a timeline computed before the run.

Actuators the controller drives (all objects of the generated IDF, see ``greenhouse_idf`` with ``RunSpec.lockstep``):
* the temperature-controlled passive venting (on/off) and the commanded vent opening (fraction of the design vent flow);
* extra air changes per hour (vents beyond the design opening, extractors);
* a signed power in kW into the zone air (a heater or a cooler as a heat source, like the lumped model);
* the heating and cooling set-points of the ideal-loads unit (None: the IDF values).

Not controllable: the shade screen (EnergyPlus gets shading by scaling the solar radiation of the weather file, which is fixed before the run), CO2 and the crop (no feedback).
EnergyPlus runs only forward: a session cannot be rewound, so resuming from a checkpoint replays the run from its start (see ``greenhouse_backend``).
"""

from __future__ import annotations

import json
import os
import socket
import subprocess
import tempfile
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Sequence

from agri_twin.domain.greenhouse_typology import GreenhouseGeometrySpec, floor_area_m2
from agri_twin.domain.models import WeatherState
from agri_twin.infrastructure.energyplus_timeline import (
    EnergyPlusInstall,
    EnergyPlusTimelineError,
    OUTDOOR_CO2_PPM,
    _epw_day,
    require_energyplus,
)
from agri_twin.infrastructure.epw_weather import EpwLocation, HourConvention, write_epw_from_states
from agri_twin.infrastructure.greenhouse_idf import EnvelopeSpec, RunSpec, ThermalSpec, build_greenhouse_idf

BRIDGE_MODULE = "agri_twin_lockstep_bridge"
BRIDGE_CLASS = "LockstepBridge"
CONNECT_TIMEOUT_SECONDS = 120.0
STEP_TIMEOUT_SECONDS = 120.0
TIMESTEPS_PER_HOUR = 4
FORECAST_BIAS_SMOOTHING = 0.7  # weight of the latest forecast error in the correction the controller applies to its forecasts (a design convention of this adapter, not a physical value)
SETPOINT_OFF_HEAT_C = -60.0   # a heating set-point nothing can fall below: the ideal heater stands down
SETPOINT_OFF_COOL_C = 200.0   # a cooling set-point nothing can exceed: the ideal cooler stands down

# Runs inside EnergyPlus (its bundled Python 3.12): imports pyenergyplus, which does not exist outside it, so the source is kept as text and written next to the IDF.
BRIDGE_SOURCE = '''"""Lock-step bridge (generated by agri_twin.infrastructure.energyplus_lockstep)."""
import json
import os
import socket

from pyenergyplus.plugin import EnergyPlusPlugin

AVERAGED = ("rh", "vent_ach")
SCHEDULES = {"auto_vent": "AUTO VENT ENABLED", "forced_vent": "FORCED VENT OPENING", "controller_ach": "CONTROLLER AIR CHANGES", "controller_heat": "CONTROLLER HEAT LEVEL",
             "heating_sp": "HEATING SETPOINT", "cooling_sp": "COOLING SETPOINT"}
VARIABLES = {"air": ("Zone Mean Air Temperature", "GREENHOUSE ZONE"), "rh": ("Zone Air Relative Humidity", "GREENHOUSE ZONE"),
             "solar": ("Enclosure Windows Total Transmitted Solar Radiation Rate", "GREENHOUSE ZONE"),
             "vent_ach": ("Zone Ventilation Standard Density Air Change Rate", "GREENHOUSE ZONE"),
             "heat_w": ("Zone Ideal Loads Zone Total Heating Rate", "HEATER"), "cool_w": ("Zone Ideal Loads Zone Total Cooling Rate", "HEATER")}


class LockstepBridge(EnergyPlusPlugin):
    def __init__(self):
        super().__init__()
        self.ready = False
        self.sock = None
        self.reader = None
        self.command = {}
        self.actuators = {}
        self.variables = {}
        self.sums = {}
        self.weight = 0.0

    def _connect(self, state):
        ex = self.api.exchange
        for key, name in SCHEDULES.items():
            handle = ex.get_actuator_handle(state, "Schedule:Constant", "Schedule Value", name)
            if handle == -1:
                self.api.runtime.issue_severe(state, "lockstep bridge: no actuator for " + name)
                return False
            self.actuators[key] = handle
        for key, (variable, zone) in VARIABLES.items():
            handle = ex.get_variable_handle(state, variable, zone)
            if handle == -1:
                self.api.runtime.issue_severe(state, "lockstep bridge: no variable " + variable)
                return False
            self.variables[key] = handle
        self.sock = socket.create_connection(("127.0.0.1", int(os.environ["AGRI_TWIN_LOCKSTEP_PORT"])), timeout=600)
        self.reader = self.sock.makefile("r", encoding="utf-8")
        self.ready = True
        return True

    def _active(self, state):
        ex = self.api.exchange
        if ex.warmup_flag(state) or not ex.api_data_fully_ready(state):
            return False
        return self.ready or self._connect(state)

    def _send(self, message):
        self.sock.sendall((json.dumps(message) + "\\n").encode("utf-8"))

    def on_begin_zone_timestep_before_set_current_weather(self, state) -> int:
        if not self._active(state):
            return 0 if not self.api.exchange.api_data_fully_ready(state) or self.api.exchange.warmup_flag(state) else 1
        ex = self.api.exchange
        self._send({"kind": "begin", "month": ex.month(state), "day": ex.day_of_month(state), "hour": ex.hour(state), "minute": ex.minutes(state)})
        line = self.reader.readline()
        if not line:
            self.api.runtime.issue_severe(state, "lockstep bridge: the controller closed the connection")
            return 1
        self.command = json.loads(line)
        return 0

    def on_begin_timestep_before_predictor(self, state) -> int:
        if not self.ready or self.api.exchange.warmup_flag(state):
            return 0
        ex = self.api.exchange
        for key, handle in self.actuators.items():
            value = self.command.get(key)
            if value is None:
                ex.reset_actuator(state, handle)
            else:
                ex.set_actuator_value(state, handle, float(value))
        return 0

    def on_end_of_system_timestep_after_hvac_reporting(self, state) -> int:
        # the zone-timestep relative humidity and ventilation rate EnergyPlus reports are means over the system timesteps inside it (they change between them): accumulate them the same way.
        # The other values are constant over the zone timestep and are read at its end.
        if not self.ready or self.api.exchange.warmup_flag(state):
            return 0
        ex = self.api.exchange
        step = ex.system_time_step(state)
        for key in AVERAGED:
            self.sums[key] = self.sums.get(key, 0.0) + step * ex.get_variable_value(state, self.variables[key])
        self.weight += step
        return 0

    def on_end_of_zone_timestep_after_zone_reporting(self, state) -> int:
        if not self.ready or self.api.exchange.warmup_flag(state):
            return 0
        ex = self.api.exchange
        values = {key: ex.get_variable_value(state, handle) for key, handle in self.variables.items()}
        if self.weight > 0.0:
            for key in AVERAGED:
                values[key] = self.sums[key] / self.weight
        self.sums, self.weight = {}, 0.0
        self._send({"kind": "end", "month": ex.month(state), "day": ex.day_of_month(state), "hour": ex.hour(state), "minute": ex.minutes(state), "values": values})
        return 0
'''


@dataclass(frozen=True, slots=True)
class LockstepCommands:
    """What the controller asks of EnergyPlus for one hour. The defaults reproduce the open-loop model (default venting and thermostat)."""

    auto_vent: bool = True
    forced_vent_fraction: float = 0.0   # fraction of the design vent flow (the commanded-ventilation event)
    controller_air_changes: float = 0.0
    controller_heat_kw: float = 0.0     # + heats the air, - cools it
    heating_setpoint_c: float | None = None
    cooling_setpoint_c: float | None = None

    def message(self) -> dict[str, Any]:
        return {"auto_vent": 1.0 if self.auto_vent else 0.0, "forced_vent": min(1.0, max(0.0, self.forced_vent_fraction)), "controller_ach": max(0.0, self.controller_air_changes),
                "controller_heat": self.controller_heat_kw, "heating_sp": self.heating_setpoint_c, "cooling_sp": self.cooling_setpoint_c}


@dataclass(frozen=True, slots=True)
class LockstepValue:
    """End-of-hour zone values (the instantaneous values of the last timestep, as the open-loop timeline reads them)."""

    air_temperature_c: float
    relative_humidity_pct: float
    radiation_w_m2: float
    ventilation_ach: float
    heating_w: float
    cooling_w: float


class LockstepSession:
    """One EnergyPlus run advanced hour by hour. Not thread-safe: one caller at a time. Use as a context manager or call ``close``."""

    def __init__(self, geometry: GreenhouseGeometrySpec, series: Sequence[tuple[datetime, WeatherState]], shading: Sequence[float], location: EpwLocation,
                 envelope: EnvelopeSpec | None = None, thermal: ThermalSpec | None = None, install: EnergyPlusInstall | None = None) -> None:
        self.install = install or require_energyplus()
        self.geometry, self.envelope, self.thermal = geometry, envelope or EnvelopeSpec(), thermal or ThermalSpec()
        self.labels = [stamp.astimezone(timezone.utc) for stamp, _ in series]
        if not self.labels or self.labels[0].minute or self.labels[0].second:
            raise EnergyPlusTimelineError("the weather series must be hourly and aligned to the hour")
        first, last = _epw_day(self.labels[0]), _epw_day(self.labels[-1])
        if (first[1], first[2]) > (last[1], last[2]) or first[0] != last[0]:
            raise EnergyPlusTimelineError("runs that cross a calendar year are not supported")
        if len({_epw_day(label) for label in self.labels}) * 24 != len(self.labels):
            raise EnergyPlusTimelineError("the weather series must cover whole EPW days (each ending at 00:00)")
        self.floor_area_m2 = floor_area_m2(geometry)
        self.max_ventilation_ach = self.thermal.max_ventilation_ach.value
        self._next = 0  # index of the hour the next call simulates
        self._folder = tempfile.TemporaryDirectory(prefix="agri_twin_ep_lockstep_")
        self._process: subprocess.Popen[str] | None = None
        self._server: socket.socket | None = None
        self._connection: socket.socket | None = None
        self._reader = None
        self._log = None
        work = Path(self._folder.name)
        idf = build_greenhouse_idf(geometry, self.envelope, self.thermal,
                                   RunSpec(first[1], first[2], last[1], last[2], timesteps_per_hour=TIMESTEPS_PER_HOUR, python_plugin_module=BRIDGE_MODULE, python_plugin_class=BRIDGE_CLASS, lockstep=True))
        self.idf_hash = idf.idf_hash
        write_epw_from_states(series, work / "weather.epw", location, HourConvention.END_OF_HOUR, solar_factors=[1.0 - min(1.0, max(0.0, f)) for f in shading])
        (work / "greenhouse.idf").write_text(idf.text, encoding="utf-8")
        (work / f"{BRIDGE_MODULE}.py").write_text(BRIDGE_SOURCE, encoding="utf-8")
        self._work = work
        try:
            self._start()
        except BaseException:
            self.close()
            raise

    # -- process ------------------------------------------------------------------------------------------------------------------------------
    def _start(self) -> None:
        self._server = socket.socket()
        self._server.bind(("127.0.0.1", 0))
        self._server.listen(1)
        self._server.settimeout(1.0)
        port = self._server.getsockname()[1]
        self._log = open(self._work / "energyplus.log", "w", encoding="utf-8")
        environment = dict(os.environ, AGRI_TWIN_LOCKSTEP_PORT=str(port))
        self._process = subprocess.Popen((str(self.install.executable), "-w", "weather.epw", "-d", "out", "greenhouse.idf"), cwd=self._work, env=environment, stdout=self._log, stderr=subprocess.STDOUT, text=True)
        waited = 0.0
        while self._connection is None:
            try:
                self._connection, _ = self._server.accept()
            except socket.timeout:
                waited += 1.0
                if self._process.poll() is not None or waited > CONNECT_TIMEOUT_SECONDS:
                    raise EnergyPlusTimelineError(f"EnergyPlus did not connect its lock-step bridge: {self._failure()}") from None
        self._connection.settimeout(STEP_TIMEOUT_SECONDS)
        self._reader = self._connection.makefile("r", encoding="utf-8")

    def _failure(self) -> str:
        error_file = self._work / "out" / "eplusout.err"
        text = error_file.read_text(encoding="utf-8", errors="replace") if error_file.exists() else ""
        severe = [line.strip() for line in text.splitlines() if "** Severe" in line or "**  Fatal" in line][:3]
        if not severe and self._log is not None:
            self._log.flush()
            text = (self._work / "energyplus.log").read_text(encoding="utf-8", errors="replace")
            severe = [line.strip() for line in text.splitlines() if "Error" in line or "error" in line][-3:]
        code = self._process.poll() if self._process is not None else None
        return f"exit {code}: {'; '.join(severe) or 'no message'}"

    def _read(self) -> dict[str, Any]:
        assert self._reader is not None
        try:
            line = self._reader.readline()
        except (socket.timeout, ConnectionError, OSError) as exc:
            raise EnergyPlusTimelineError(f"the EnergyPlus lock-step bridge stopped answering: {exc}; {self._failure()}") from exc
        if not line:
            raise EnergyPlusTimelineError(f"EnergyPlus ended before the hour was simulated: {self._failure()}")
        return json.loads(line)

    def _send(self, message: dict[str, Any]) -> None:
        assert self._connection is not None
        self._connection.sendall((json.dumps(message) + "\n").encode("utf-8"))

    # -- stepping -----------------------------------------------------------------------------------------------------------------------------
    @property
    def hours_simulated(self) -> int:
        return self._next

    @property
    def next_label(self) -> datetime | None:
        """The end of the next hour to simulate (None when the series is exhausted)."""
        return self.labels[self._next] if self._next < len(self.labels) else None

    def advance(self, label: datetime, commands: LockstepCommands) -> LockstepValue:
        """Simulate the hour that ends at ``label`` with ``commands`` held. Hours must be requested in order, once each."""
        label = label.astimezone(timezone.utc)
        if self._next >= len(self.labels) or label != self.labels[self._next]:
            raise EnergyPlusTimelineError(f"the lock-step session expected the hour ending {self.labels[self._next].isoformat() if self._next < len(self.labels) else 'nothing'}, asked for {label.isoformat()}")
        _, month, day = _epw_day(label)
        end_hour = 24 if label.hour == 0 else label.hour
        message = commands.message()
        last: dict[str, Any] | None = None
        for step in range(TIMESTEPS_PER_HOUR):
            begin = self._read()
            expected = (month, day, end_hour - 1, 60 // TIMESTEPS_PER_HOUR * step)
            seen = (begin.get("month"), begin.get("day"), begin.get("hour"), begin.get("minute"))
            if begin.get("kind") != "begin" or (seen[0], seen[1]) != expected[:2] or seen[2] not in (expected[2], expected[2] + 1):
                raise EnergyPlusTimelineError(f"EnergyPlus is at {seen} but the controller is at {expected}")
            self._send(message)
            end = self._read()
            if end.get("kind") != "end":
                raise EnergyPlusTimelineError(f"unexpected lock-step message {end.get('kind')!r}")
            last = end
        self._next += 1
        values = last["values"]  # type: ignore[index]
        return LockstepValue(values["air"], min(100.0, max(0.0, values["rh"])), max(0.0, values["solar"]) / self.floor_area_m2, max(0.0, values["vent_ach"]),
                             max(0.0, values["heat_w"]), max(0.0, values["cool_w"]))

    def close(self) -> None:
        for connection in (self._connection, self._server):
            try:
                if connection is not None:
                    connection.close()
            except OSError:
                pass
        process = self._process
        if process is not None and process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=15)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait(timeout=15)
        if self._log is not None:
            self._log.close()
        self._connection = self._server = self._reader = self._log = None
        try:
            self._folder.cleanup()
        except OSError:
            pass

    def __enter__(self) -> "LockstepSession":
        return self

    def __exit__(self, *_exc: object) -> None:
        self.close()


