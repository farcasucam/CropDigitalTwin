def commands_from_actuators(actuators: Any) -> LockstepCommands:
    """Translate the actuator mapping the runner hands the greenhouse (events and controller, already merged) into EnergyPlus commands.

    "ventilation" is a manual event: a fraction of the vent capacity on top of the default venting. "ventilation_ach" comes from a controller: physical air changes, and the default venting
    stands down. "heating" and "cooling" (kW, from a controller or an event) become one signed power into the air, and each makes the thermostat of the ideal-loads unit stand down. The
    shade screen cannot be driven in lock-step (shading is applied to the weather file before the run): manual shading events are in the file, a controller cannot use it.
    """
    forced, controller_ach, heat_kw, cool_kw = 0.0, 0.0, 0.0, 0.0
    auto_vent, heating_driven, cooling_driven = True, False, False
    for name, value in (actuators or {}).items():
        actual = float(value.actual if hasattr(value, "actual") else getattr(value, "actual_value", 0.0))
        if name in ("ventilation", "vent"):
            forced = actual
        elif name == "ventilation_ach":
            auto_vent, controller_ach = False, actual
        elif name in ("heating", "heat"):
            heating_driven, heat_kw = True, actual
        elif name in ("cooling", "cool"):
            cooling_driven, cool_kw = True, actual
    return LockstepCommands(auto_vent, forced, controller_ach, heat_kw - cool_kw, SETPOINT_OFF_HEAT_C if heating_driven else None, SETPOINT_OFF_COOL_C if cooling_driven else None)


class LockstepMicroclimateEngine:
    """The greenhouse engine of a lock-step EnergyPlus run: the orchestrator calls it once per hour and it advances the EnergyPlus session by that hour."""

    requires_simulation_time = True

    def __init__(self, session: LockstepSession, forecast_model: Any = None) -> None:
        """``forecast_model``: an optional lumped model of the same greenhouse (``GeometryGreenhouseEngine``) the controller uses to look one step ahead, as a real controller uses an imperfect model of its
        greenhouse. It is never the source of a result: EnergyPlus is. Its floor node (which EnergyPlus' state does not expose) is kept in step by running it alongside, from EnergyPlus' own air state."""
        self.session = session
        self.forecast_model = forecast_model
        self._floor_temperature_c: float | None = None
        self._bias_c = 0.0  # how much warmer (+) EnergyPlus ended the last hour than the forecast model said for the commands actually sent

    @property
    def configuration(self):
        return self.forecast_model.configuration if self.forecast_model is not None else None

    def _with_floor(self, prior):
        if prior is None or self._floor_temperature_c is None:
            return prior
        from agri_twin.domain.greenhouse import GreenhouseMicroclimateState

        return GreenhouseMicroclimateState(**{**prior.to_dict(), "floor_temperature_c": self._floor_temperature_c})

    def predict_air_temperature(self, weather: WeatherState, prior, dt_seconds: float, mode: str = "passive_greenhouse", extra_air_changes: float = 0.0, net_hvac_kw: float = 0.0, shade: float = 0.0) -> float:
        if self.forecast_model is None:
            raise AttributeError("no forecast model")
        return self.forecast_model.predict_air_temperature(weather, self._with_floor(prior), dt_seconds, mode, extra_air_changes, net_hvac_kw, shade) + self._bias_c

    def advance(self, weather: WeatherState, crop, dt_seconds: float, mode: str = "passive_greenhouse", actuators=None, prior=None, simulation_time: datetime | None = None):
        from dataclasses import replace

        from agri_twin.domain.greenhouse import (
            CropMicroclimateFeedback,
            GreenhouseMicroclimateResult,
            GreenhouseMicroclimateState,
            GreenhouseModelError,
            MicroclimateState,
            derived_environment,
            vapour_pressure_deficit_kpa,
        )

        if simulation_time is None:
            raise GreenhouseModelError("the EnergyPlus backend needs the simulation time of the step")
        if dt_seconds != 3600.0:
            raise GreenhouseModelError("the EnergyPlus lock-step backend advances whole hours")
        label = simulation_time.astimezone(timezone.utc)
        while self.session.next_label is not None and self.session.next_label < label:  # a campaign that does not start at midnight: EnergyPlus starts at midnight, so the hours before are spun up uncommanded
            self.session.advance(self.session.next_label, LockstepCommands())
        commands = commands_from_actuators(actuators)
        if self.forecast_model is not None:  # keep the forecast model's floor node in step with EnergyPlus' air (before this hour: the state the controller decided from)
            model = self.forecast_model
            shadow = model.step(weather, replace(model.configuration, mode=mode), model._normalize_actuators(model._scaled(actuators)), CropMicroclimateFeedback(), dt_seconds, prior=self._with_floor(prior))
            self._floor_temperature_c = shadow.floor_temperature_c
        value = self.session.advance(label, commands)
        if self.forecast_model is not None:
            self._bias_c = FORECAST_BIAS_SMOOTHING * (value.air_temperature_c - shadow.air_temperature_c) + (1.0 - FORECAST_BIAS_SMOOTHING) * self._bias_c
        heating_kw = value.heating_w / 1000.0 + max(0.0, commands.controller_heat_kw)
        cooling_kw = value.cooling_w / 1000.0 + max(0.0, -commands.controller_heat_kw)
        state = MicroclimateState(
            air_temperature_c=value.air_temperature_c, relative_humidity_pct=value.relative_humidity_pct,
            vpd_kpa=vapour_pressure_deficit_kpa(value.air_temperature_c, value.relative_humidity_pct), pressure_hpa=weather.pressure_hpa,
            solar_radiation_w_m2=value.radiation_w_m2, par_umol_m2_s=value.radiation_w_m2 * 2.04, co2_ppm=OUTDOOR_CO2_PPM,
            wind_speed_m_s=weather.wind_speed_m_s, ventilation_fraction=min(1.0, value.ventilation_ach / self.session.max_ventilation_ach), heating_kw=heating_kw, cooling_kw=cooling_kw,
            shading_fraction=self._commanded_shading(actuators), temperature_c=value.air_temperature_c)
        return GreenhouseMicroclimateResult(derived_environment(state), GreenhouseMicroclimateState(**state.to_dict()), 0.0, 0.0)

    @staticmethod
    def _commanded_shading(actuators) -> float:
        control = (actuators or {}).get("shade") or (actuators or {}).get("shading")
        return float(control.actual) if control is not None else 0.0
